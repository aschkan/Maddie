export interface SeedInterviewOptions {
  /** How many participants to write, from the top. Defaults to all of them. */
  total?: number;
  /** Epoch ms to count the fieldwork window back from. Defaults to now. */
  now?: number;
  /** Spread the sittings over this many days back from `now`. */
  days?: number;
}

export const DEFAULT_INTERVIEW_TOTAL = PARTICIPANTS.length;

/**
 * Build the synthetic interviews.
 *
 * Pure and deterministic — no clock unless one is passed, no `Math.random`, no
 * database — so the tests can check what the seed will write without running
 * the seed. `source` is forced to `"example"` here and nowhere else: it is not
 * a field in the table above, so there is no line to forget to add.
 */
export function buildSeedInterviews(options: SeedInterviewOptions = {}): Interview[] {
  const wanted = Math.max(0, Math.min(PARTICIPANTS.length, Math.floor(options.total ?? DEFAULT_INTERVIEW_TOTAL)));
  const now = options.now ?? Date.now();
  const days = Math.max(1, options.days ?? 45);
  const chosen = PARTICIPANTS.slice(0, wanted);
  if (chosen.length === 0) return [];

  // Spread the sittings evenly backwards over the window, oldest first, so the
  // list reads like fieldwork rather than like twenty-four rows written at
  // once. Evenly rather than randomly: a deterministic gap is one fewer thing
  // that can differ between two reseeds.
  const step = chosen.length > 1 ? (days - 1) / (chosen.length - 1) : 0;

  return chosen.map((draft, index) => {
    const daysBack = Math.round((chosen.length - 1 - index) * step);
    const when = new Date(now - daysBack * 86_400_000);
    // Midday, so a date rendered in any timezone stays on the same day. A
    // sitting stamped at 23:30 UTC is the previous day in Amsterdam.
    when.setUTCHours(12, 0, 0, 0);
    return {
      ...draft,
      id: `seed-interview-${draft.code.toLowerCase()}`,
      source: "example",
      conductedAt: when.toISOString(),
    };
  });
}
